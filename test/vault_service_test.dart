import 'dart:io';
import 'dart:typed_data';

import 'package:flutter_test/flutter_test.dart';
import 'package:vaultly/core/crypto/encoding.dart';
import 'package:vaultly/core/import_export/legacy_backup.dart';
import 'package:vaultly/data/vault_envelope.dart';
import 'package:vaultly/data/vault_item.dart';
import 'package:vaultly/data/vault_service.dart';
import 'package:vaultly/data/vault_storage.dart';

VaultItem _item(String id, {String title = 'Example', String pw = 'pw'}) {
  final now = DateTime(2026, 1, 1);
  return VaultItem(
    id: id,
    title: title,
    username: 'me@example.com',
    password: pw,
    urls: ['https://example.com/login'],
    createdAt: now,
    updatedAt: now,
  );
}

void main() {
  late Directory dir;
  late VaultService vault;

  setUp(() async {
    dir = await Directory.systemTemp.createTemp('vaultly_test');
    vault = VaultService(VaultStorage(dir));
  });

  tearDown(() => dir.delete(recursive: true));

  test('create, lock and unlock with the master password', () async {
    expect(await vault.exists(), isFalse);
    await vault.create('correct horse battery staple');
    await vault.save(_item('a'));
    vault.lock();
    expect(vault.isUnlocked, isFalse);

    final fresh = VaultService(VaultStorage(dir));
    await fresh.unlock('correct horse battery staple');
    expect(fresh.activeItems.single.title, 'Example');
  });

  test('wrong master password is rejected', () async {
    await vault.create('right');
    vault.lock();
    expect(() => vault.unlock('wrong'),
        throwsA(isA<WrongPasswordException>()));
  });

  test('nothing sensitive is stored in plaintext on disk', () async {
    await vault.create('master');
    await vault.save(_item('a', title: 'SuperSecretBank', pw: 'hunter2xyz'));
    final raw = await VaultStorage(dir).vaultFile.readAsString();
    expect(raw, isNot(contains('SuperSecretBank')));
    expect(raw, isNot(contains('hunter2xyz')));
    expect(raw, isNot(contains('example.com')));
  });

  test('vault key unlock (biometrics path) and master password change',
      () async {
    await vault.create('old-password');
    await vault.save(_item('a'));
    final key = vault.vaultKey;
    await vault.changeMasterPassword('old-password', 'new-password');
    vault.lock();

    expect(() => vault.unlock('old-password'),
        throwsA(isA<WrongPasswordException>()));
    await vault.unlock('new-password');
    vault.lock();
    // The vault key is unchanged, so biometric unlock keeps working.
    await vault.unlockWithKey(key);
    expect(vault.activeItems, hasLength(1));
  });

  test('password history is recorded when a password changes', () async {
    await vault.create('m');
    final saved = await vault.save(_item('a', pw: 'first'));
    await vault.save(saved.copyWith(password: 'second'));
    final item = vault.byId('a')!;
    expect(item.password, 'second');
    expect(item.passwordHistory.single.password, 'first');
  });

  test('recently deleted: trash, restore, delete forever', () async {
    await vault.create('m');
    await vault.save(_item('a'));
    await vault.moveToTrash('a');
    expect(vault.activeItems, isEmpty);
    expect(vault.byId('a')!.isDeleted, isTrue);
    await vault.restore('a');
    expect(vault.activeItems, hasLength(1));
    await vault.moveToTrash('a');
    await vault.emptyTrash();
    expect(vault.data.items, isEmpty);
  });

  test('encrypted backup export → import into another vault', () async {
    await vault.create('m');
    await vault.save(_item('a', title: 'One'));
    await vault.save(_item('b', title: 'Two'));
    final backup = await vault.exportBackup('backup-pw');
    expect(backup, isNot(contains('One')));

    final dir2 = await Directory.systemTemp.createTemp('vaultly_test2');
    final other = VaultService(VaultStorage(dir2));
    await other.create('other');
    expect(() => other.importBackup(backup, 'nope'),
        throwsA(isA<WrongPasswordException>()));
    expect(await other.importBackup(backup, 'backup-pw'), 2);
    // Importing the same file again does not create duplicates.
    expect(await other.importBackup(backup, 'backup-pw'), 0);
    await dir2.delete(recursive: true);
  });

  test('a backup file cannot be opened as the live vault', () async {
    await vault.create('m');
    final backup = await vault.exportBackup('m');
    expect(() => VaultEnvelope.decode(backup, expect: EnvelopeKind.vault),
        throwsA(isA<VaultFormatException>()));
  });

  test('imports a real Vaultly 1.x backup (made with encrypt 5.0.3)',
      () async {
    // Generated by the original 1.x exportVaultToString().
    // Hex-encoded so secret scanners don't mistake the base64 for a token.
    final legacy = String.fromCharCodes(hexDecode(
        '744837505358594f4a356657615a62434953617632673d3d3a56587238356550'
        '737276375653675a4b6b366579696e354475594a303451707a5a466a4c37594e'
        '7350644253597a433643324e49626677795a366167376d715a696e6f39705834'
        '6e344d484e7834534e6f67444b6a76492b3850367655726a6e70723536783141'
        '426c456d52576f6d41703054345377616a623139576c782b6574575663544642'
        '76596c68656b55516e6c53556d4b536e6f762f456c6348342f7a7764574b4432'
        '594b4e31714a6d2b7247622b304d377a6976484c774e314334763866566b2f30'
        '314e52716154524c62667144357572593834745a4b453647587a42563658472f'
        '7049624f572f74594d6a636336352b3576744959424271746e614c6e36374f47'
        '7130647851373043324e32796855773d3d'));
    expect(LegacyBackup.looksLegacy(legacy), isTrue);
    final items = LegacyBackup.decrypt(legacy, 'backup-pass');
    expect(items.map((i) => i.title), ['Netflix', 'GitHub']);
    expect(items.first.password, 'p@ss "w0rd"');
    expect(() => LegacyBackup.decrypt(legacy, 'wrong'), throwsFormatException);

    await vault.create('m');
    expect(await vault.importBackup(legacy, 'backup-pass'), 2);
  });

  test('passkey registration attaches to a matching login', () async {
    await vault.create('m');
    await vault.save(_item('a'));
    final (item, _) = await vault.registerPasskey(
      '{"rp":{"id":"example.com","name":"Example"},'
      '"user":{"id":"dXNlcg","name":"me@example.com","displayName":"Me"},'
      '"challenge":"Y2hhbGxlbmdl","pubKeyCredParams":[{"type":"public-key","alg":-7}]}',
      origin: 'https://example.com',
    );
    expect(item.id, 'a');
    expect(vault.passkeyItemsFor('example.com'), hasLength(1));
    final response = await vault.assertPasskey(
      'a',
      '{"rpId":"example.com","challenge":"YWJj"}',
      origin: 'https://example.com',
    );
    expect(response, contains('"signature"'));
    expect(vault.byId('a')!.passkey!.lastUsedAt, isNotNull);
  });

  test('website icons are stored encrypted and survive reload', () async {
    await vault.create('m');
    final item = await vault.save(_item('a'));
    final icon = Uint8List.fromList(List.generate(64, (i) => i));
    await vault.setIcon('a', icon);
    expect(vault.byId('a')!.updatedAt, item.updatedAt);
    vault.lock();
    await vault.unlock('m');
    expect(vault.byId('a')!.icon, icon);
    await vault.removeAllIcons();
    expect(vault.byId('a')!.icon, isNull);
  });

  test('generator history keeps the most recent passwords', () async {
    await vault.create('m');
    await vault.rememberGenerated('one');
    await vault.rememberGenerated('two');
    await vault.rememberGenerated('two');
    expect(vault.data.generated.map((g) => g.value), ['two', 'one']);
  });
}
